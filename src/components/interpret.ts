export function computeHealth(d: Derived, th: Thresholds): { health: Health; descKey: TranslationKey } {
  const statuses: string[] = [];
  if (d.moisture !== null) statuses.push(moistureStatus(d.moisture, th.moisture));
  if (d.soilTemp !== null) statuses.push(temperatureStatus(d.soilTemp, th.temperature));
  if (d.npkValid) {
    const thN = th.npk;
    if (d.nitrogen !== null) statuses.push(npkStatus(d.nitrogen, thN.nitrogen.min, thN.nitrogen.max));
    if (d.phosphorus !== null) statuses.push(npkStatus(d.phosphorus, thN.phosphorus.min, thN.phosphorus.max));
    if (d.potassium !== null) statuses.push(npkStatus(d.potassium, thN.potassium.min, thN.potassium.max));
  }
  const goods = statuses.filter((s) => s === 'good' || s === 'optimal').length;
  const bads = statuses.filter((s) => s === 'critical' || s === 'high' || s === 'low').length;
  if (!statuses.length) return { health: 'moderate', descKey: 'insufficient' };
  if (bads >= 2 || goods <= 1) return { health: 'poor', descKey: 'poorDesc' };
  if (goods < statuses.length) return { health: 'moderate', descKey: 'modDesc' };
  return { health: 'good', descKey: 'goodDesc' };
}

export function buildActions(d: Derived, w: WeatherData, th: Thresholds): Action[] {
  const actions: Action[] = [];
  if (d.moisture !== null) {
    if (d.moisture < th.moisture.irrigateNow && (w.temp === null || w.temp > th.temperature.hotDay))
      actions.push({ kind: 'urgent', titleKey: 'irrNow', detailKey: 'irrNowD' });
    else if (d.moisture < th.moisture.planIrrigation && (w.rain === null || w.rain < 30))
      actions.push({ kind: 'warn', titleKey: 'irrSoon', detailKey: 'irrSoonD' });
  }
  if (d.npkValid) {
    const thN = th.npk;
    if (d.nitrogen !== null && d.nitrogen < thN.nitrogen.min) actions.push({ kind: 'warn', titleKey: 'addN', detailKey: 'addND' });
    if (d.phosphorus !== null && d.phosphorus < thN.phosphorus.min) actions.push({ kind: 'warn', titleKey: 'addP', detailKey: 'addPD' });
    if (d.potassium !== null && d.potassium < thN.potassium.min) actions.push({ kind: 'warn', titleKey: 'addK', detailKey: 'addKD' });
  }
  if (actions.length === 0) actions.push({ kind: 'ok', titleKey: 'allGood', detailKey: 'allGoodD' });
  return actions;
}

