export function num(v: unknown): number | null {
  return typeof v === 'number' && Number.isFinite(v) ? v : null;
}

export function moistureStatus(m: number, th: Thresholds['moisture']): Tone {
  if (m < th.veryDry) return 'crit';
  if (m < th.belowIdeal || m > th.waterlogRisk) return 'warn';
  return 'good';
}

export function temperatureStatus(t: number, th: Thresholds['temperature']): Tone {
  if (t < th.min || t > th.max) return 'crit';
  return 'good';
}

export function npkStatus(v: number, min: number, max: number): 'low' | 'optimal' | 'high' {
  if (v < min) return 'low';
  if (v > max) return 'high';
  return 'optimal';
}

export function npkTone(s: 'low' | 'optimal' | 'high'): Tone {
  return s === 'optimal' ? 'good' : s === 'low' ? 'warn' : 'crit';
}

export interface Derived {
  moisture: number | null;
  soilTemp: number | null;
  nitrogen: number | null;
  phosphorus: number | null;
  potassium: number | null;
  npkValid: boolean;
  temperatureValid: boolean;
}

export function derive(r: TelemetryReading): Derived {
  return {
    moisture: num(r.soilMoisture),
    soilTemp: num(r.soilTemperature),
    nitrogen: num(r.nitrogen),
    phosphorus: num(r.phosphorus),
    potassium: num(r.potassium),
    npkValid: r.npkValid === true,
    temperatureValid: r.temperatureValid === true,
  };
}

